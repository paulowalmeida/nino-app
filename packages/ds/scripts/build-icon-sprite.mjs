/**
 * Bundles every file in src/assets/icons into a single <symbol> sprite.
 *
 * Run after adding or removing an icon: `npm run icons:sprite -w @nino/ds`.
 * The generated sprite is committed so apps, Storybook and tests all resolve
 * it without depending on a build step running first.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const iconsDir = join(here, '..', 'src', 'assets', 'icons')
const spritePath = join(here, '..', 'src', 'assets', 'icons.sprite.svg')
const typesPath = join(here, '..', 'src', 'components', 'Icon', 'Icon.types.ts')

const ROOT_ATTRIBUTES = /<svg([^>]*)>/
const INNER_CONTENT = /<svg[^>]*>([\s\S]*)<\/svg>/

const names = readdirSync(iconsDir)
  .filter((file) => file.endsWith('.svg'))
  .map((file) => file.replace(/\.svg$/, ''))
  .sort()

const symbols = names.map((name) => {
  const source = readFileSync(join(iconsDir, `${name}.svg`), 'utf8')

  /*
   * width/height do arquivo original (14x14 num viewBox 0 0 24 24, por
   * exemplo) não podem ir pro <symbol>: um <use> que referencia um symbol
   * com width/height próprios monta um viewport interno nesse tamanho,
   * ancorado no canto superior-esquerdo em vez de preencher a caixa do
   * <svg> que consome — o ícone renderiza deslocado. Só o viewBox deve
   * reger a escala.
   */
  const attributes = source
    .match(ROOT_ATTRIBUTES)[1]
    .replace(/\s+/g, ' ')
    .replace(/\swidth="[^"]*"/, '')
    .replace(/\sheight="[^"]*"/, '')
    .trim()

  const content = source
    .match(INNER_CONTENT)[1]
    .trim()
    .split('\n')
    .map((line) => `    ${line.trim()}`)
    .join('\n')

  return `  <symbol id="${name}" ${attributes}>\n${content}\n  </symbol>`
})

const sprite = [
  '<svg xmlns="http://www.w3.org/2000/svg" style="display: none">',
  ...symbols,
  '</svg>',
  '',
].join('\n')

writeFileSync(spritePath, sprite)

const iconNameType = [
  '// Generated by scripts/build-icon-sprite.mjs — do not edit by hand.',
  '',
  'export const ICON_NAMES = [',
  ...names.map((name) => `  '${name}',`),
  '] as const',
  '',
  'export type IconName = (typeof ICON_NAMES)[number]',
  '',
].join('\n')

writeFileSync(typesPath, iconNameType)

console.log(`Sprite written with ${names.length} icons.`)
